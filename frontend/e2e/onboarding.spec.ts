import {test,expect} from '@playwright/test'
for(const kind of ['SCHOOL','COLLEGE']){
 test(`${kind}: password signup, login, workspace, scheduling, invitation and logout`,async({page})=>{
  const email=kind.toLowerCase()+'@institution.example',password='Private registration passphrase!'
  await page.goto('/sign-up')
  await page.getByLabel('Name',{exact:true}).fill('New Institution Owner')
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign up',exact:true}).click()
  await expect(page).toHaveURL(/sign-in$/)
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Welcome to CampusFlow'})).toBeVisible()
  expect((await page.request.get('/api/product/catalog')).status()).toBe(403)
  await page.reload()
  await expect(page.getByRole('heading',{name:'Welcome to CampusFlow'})).toBeVisible()
  await page.getByRole('combobox',{name:'Institution Type',exact:true}).selectOption(kind)
  await page.getByLabel('Institution Name').fill('New '+kind)
  await page.getByRole('button',{name:'Create workspace',exact:true}).click()
  await expect(page.getByText('A clearer week starts here.')).toBeVisible()
  await page.goto('/sign-up')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByText('A clearer week starts here.')).toBeVisible()
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByRole('button',{name:'Load demo catalog'}).click()
  await expect(page.getByRole('status')).toContainText('Demo catalog loaded')
  const seeded=(await (await page.request.get('/api/product/catalog')).json()).data
  await page.getByRole('link',{name:kind==='SCHOOL'?'Teachers':'Faculty',exact:true}).click()
  await expect(page.getByRole('heading',{name:kind==='SCHOOL'?'Teachers':'Faculty',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Generate timetable',exact:true}).click()
  await page.getByLabel('Timetable name').fill(kind+' published timetable')
  await page.getByLabel('Scheduling engine').selectOption('csp')
  await page.getByRole('button',{name:'Generate timetable',exact:true}).click()
  await expect(page.getByText('A complete schedule is ready.')).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'Save as a new version'}).click()
  await expect(page.getByRole('button',{name:/Session /})).toHaveCount(kind==='SCHOOL'?14:16)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Publish',exact:true}).click()
  await expect(page.getByText('Protected version',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Users & access',exact:true}).click()
  const invited=kind.toLowerCase()+'-member@institution.example'
  await page.getByLabel('Invitation email',{exact:true}).fill(invited)
  await page.getByRole('combobox',{name:'Invitation role',exact:true}).selectOption(kind==='SCHOOL'?'teacher':'student')
  if(kind==='SCHOOL')await page.getByRole('combobox',{name:'Teacher / faculty record',exact:true}).selectOption(seeded.faculty[0].id)
  else await page.getByRole('checkbox',{name:seeded.batches[0].id,exact:true}).check()
  await page.getByRole('button',{name:'Create invitation',exact:true}).click()
  await expect(page.getByLabel('Private invitation link')).toBeVisible()
  const invitation=await page.getByLabel('Private invitation link').inputValue()
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await expect(page).toHaveURL(/sign-in$/)
  await page.goto(invitation)
  await page.getByLabel('Password',{exact:true}).fill('Invited private passphrase!')
  await page.getByRole('button',{name:'Accept invitation',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Invitation accepted')
  await page.getByRole('link',{name:'Sign In',exact:true}).click()
  await page.getByLabel('Email',{exact:true}).fill(invited)
  await page.getByLabel('Password',{exact:true}).fill('Invited private passphrase!')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('button',{name:'Sign out',exact:true})).toBeVisible()
  await page.goto('/timetables')
  await page.getByRole('combobox',{name:'Timetable version'}).selectOption({label:kind+' published timetable · published'})
  await expect(page.getByRole('button',{name:/Session /}).first()).toBeVisible()
  await expect(page.getByRole('link',{name:'Users & access',exact:true})).toHaveCount(0)
  expect((await page.request.get('/api/product/catalog')).status()).toBe(403)
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.reload()
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible()
  expect((await page.request.get('/api/product/catalog')).status()).toBe(401)
 })
}
