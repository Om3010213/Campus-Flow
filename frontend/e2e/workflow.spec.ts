import { test, expect } from '@playwright/test'

test('real administrator workflow: catalog, generation, draft, publish, report, export',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/settings')
  await page.getByLabel('Email', {exact:true}).fill('browser-admin')
  await page.getByLabel('Password', {exact:true}).fill('Browser test password 123!')
  await page.getByRole('button', {name:'Sign in', exact:true}).click()
  await expect(page.getByRole('button',{name:'Sign out',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByRole('button',{name:'Load demo catalog'}).click()
  await expect(page.getByRole('status')).toContainText(/Demo catalog loaded|empty catalog/)
  await page.getByRole('link',{name:'Faculty',exact:true}).click()
  await expect(page.getByText('Dr. Asha Mehta')).toBeVisible()
  await page.getByRole('button',{name:'Edit F101',exact:true}).click()
  await page.getByLabel('Full name').fill('Dr. Asha Mehta')
  await page.getByRole('button',{name:'Save record'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link',{name:'Generate timetable',exact:true}).click()
  await page.getByLabel('Timetable name').fill('Browser verified timetable')
  await page.getByLabel('Scheduling engine').selectOption('csp')
  await page.getByRole('button',{name:'Generate timetable',exact:true}).click()
  await expect(page.getByText('A complete schedule is ready.')).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'Save as a new version'}).click()
  await expect(page.getByRole('heading',{name:'Browser verified timetable'})).toBeVisible()
  await expect(page.getByRole('button',{name:/Session /})).toHaveCount(16)
  await page.getByRole('button',{name:'Session CS201-A:1',exact:true}).click()
  const originalDay=await page.getByRole('combobox',{name:'Day',exact:true}).inputValue()
  const originalStart=await page.getByRole('combobox',{name:'Start time',exact:true}).inputValue()
  const originalRoom=await page.getByRole('combobox',{name:'Classroom',exact:true}).inputValue()
  await page.getByRole('button',{name:'Remove session'}).click()
  await page.getByRole('button',{name:'Save draft'}).click()
  await expect(page.getByText('Draft saved.')).toBeVisible()
  await expect(page.getByRole('button',{name:'Publish',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Add missing session (1)'}).click()
  await page.getByRole('combobox',{name:'Day',exact:true}).selectOption(originalDay)
  await page.getByRole('combobox',{name:'Start time',exact:true}).selectOption(originalStart)
  await page.getByRole('combobox',{name:'Classroom',exact:true}).selectOption(originalRoom)
  await page.getByRole('button',{name:'Apply to unsaved draft'}).click()
  await page.getByRole('button',{name:'Validate',exact:true}).click()
  await expect(page.getByText('All sessions pass validation.')).toBeVisible()
  await page.getByRole('button',{name:'Save draft'}).click()
  await expect(page.getByText('Draft saved.')).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Publish',exact:true}).click()
  await expect(page.getByText('Protected version', {exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/timetable-desktop.png',fullPage:true})
  await page.getByRole('link',{name:'Workload reports & exports →'}).click()
  await expect(page.getByText('Faculty workload',{exact:true})).toBeVisible()
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('link',{name:'Export PDF'}).click()
  const download=await downloadEvent
  await download.saveAs('test-results/export.pdf')
  await page.getByRole('link',{name:'Overview',exact:true}).click()
  await expect(page.getByText('A clearer week starts here.')).toBeVisible()
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('link',{name:'Subjects',exact:true}).click()
  await expect(page.getByText('Data Structures', {exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/mobile.png',fullPage:true})
  const session=await (await page.request.get('/api/auth/session')).json()
  const created=await page.request.post('/api/auth/users',{headers:{'X-CSRF-Token':session.data.csrf_token},data:{username:'browser-viewer',password:'Temporary viewer phrase!',role:'viewer',scopes:['College']}})
  expect(created.status()).toBe(201)
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.getByLabel('Email',{exact:true}).fill('browser-viewer')
  await page.getByLabel('Password',{exact:true}).fill('Temporary viewer phrase!')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByLabel('Current password',{exact:true}).fill('Temporary viewer phrase!')
  await page.getByLabel('New password',{exact:true}).fill('My private viewer phrase!')
  await page.getByLabel('Confirm new password',{exact:true}).fill('My private viewer phrase!')
  await page.getByRole('button',{name:'Change password',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Change your temporary password',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Sign out',exact:true})).toBeVisible()
  await page.goto('/subjects')
  await expect(page.getByRole('alert')).toContainText('permission')
  await page.goto('/timetables')
  await page.getByRole('combobox',{name:'Timetable version'}).selectOption({label:'Browser verified timetable · published'})
  await expect(page.getByRole('button',{name:/Session /})).toHaveCount(16)
  await expect(page.getByRole('button',{name:'Publish',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Duplicate draft'})).toHaveCount(0)
  await expect(page.getByRole('link',{name:'Plan faculty absence →'})).toHaveCount(0)
  await page.getByRole('button',{name:'Session CS201-A:1',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Day',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Remove session'})).toHaveCount(0)
  expect(errors).toEqual([])
})
